import { URL } from 'node:url';
import process from 'node:process';
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const result = await build({
  absWorkingDir: root.pathname,
  entryPoints: ['ui/main.ts'],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  legalComments: 'inline',
});
const template = await readFile(new URL('ui/panel.html', root), 'utf8');
const html = template.replace('__UPLOAD_SCRIPT__', () =>
  result.outputFiles[0].text.replaceAll('</script', '<\\/script'),
);
const generated =
  '// Generated by npm run ui:build. Do not edit.\nexport const UPLOAD_HTML = ' +
  JSON.stringify(html) +
  ';\n';
const destination = new URL('src/ui/panel.generated.ts', root);
if (process.argv.includes('--check')) {
  if ((await readFile(destination, 'utf8')) !== generated)
    throw Error('Upload panel bundle is stale. Run npm run ui:build.');
} else await writeFile(destination, generated);
